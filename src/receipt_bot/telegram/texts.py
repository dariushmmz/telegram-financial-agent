_PERSIAN_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def _number(value: int) -> str:
    return f"{value:,}".translate(_PERSIAN_DIGITS).replace(",", "٬")


def cleanup_preview_text(*, count: int, total_bytes: int, retention_days: int, cutoff: str) -> str:
    return (
        "🧹 پیش‌نمایش پاک‌سازی تصاویر رسید\n"
        f"دوره نگهداری: {_number(retention_days)} روز\n"
        f"قدیمی‌تر از: {cutoff}\n"
        f"تعداد تصاویر واجد شرایط: {_number(count)}\n"
        f"فضای تخمینی قابل آزادسازی: {_number(total_bytes)} بایت\n\n"
        "فقط فایل تصویر حذف می‌شود. اطلاعات استخراج‌شده، پرداخت‌ها، تخصیص‌ها، "
        "گزارش‌ها و تاریخچه حسابداری باقی می‌مانند."
    )


def cleanup_final_text(*, count: int, total_bytes: int) -> str:
    return (
        "⚠️ تأیید نهایی پاک‌سازی\n"
        f"در صورت ادامه، {_number(count)} فایل تصویر با حجم تخمینی "
        f"{_number(total_bytes)} بایت برای همیشه حذف می‌شود.\n"
        "سوابق مالی حذف نخواهند شد. این عملیات برای فایل‌های حذف‌شده قابل بازگشت نیست."
    )


def cleanup_result_text(
    *, deleted: int, deleted_bytes: int, missing: int, failed: int
) -> str:
    return (
        "✅ پاک‌سازی پایان یافت.\n"
        f"حذف‌شده: {_number(deleted)} فایل ({_number(deleted_bytes)} بایت)\n"
        f"از قبل موجود نبود: {_number(missing)}\n"
        f"ناموفق/ناامن: {_number(failed)}\n"
        "همه سوابق مالی و حسابداری حفظ شده‌اند."
    )
