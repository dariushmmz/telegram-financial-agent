def reviewer_prompt(action: str) -> str:
    verb = "افزودن" if action == "grant" else "حذف"
    return f"کاربر موردنظر برای {verb} نقش حسابدار را با دکمه زیر انتخاب کنید."


def reviewer_changed(display_name: str, active: bool) -> str:
    verb = "اضافه شد" if active else "حذف شد"
    return f"✅ {display_name} به‌عنوان حسابدار {verb}."


